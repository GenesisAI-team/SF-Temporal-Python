async def _generate_h2_history(
    env: Any, data: IssueWorkflowInput, workflow_id: str
) -> tuple[IssueWorkflowResult, Any]:
    """Run the reference H2 implementation and return (result, history)."""
    async with Worker(
        env.client,
        task_queue=TASK_QUEUE,
        workflows=[H2IssueWorkflow],
        activities=list(_ACTIVITIES),
    ):
        handle = await env.client.start_workflow(
            H2IssueWorkflow.run,
            data,
            id=workflow_id,
            task_queue=TASK_QUEUE,
            memo={"issue_id": data.issue_id},
        )
        result = await handle.result()
        history = await handle.fetch_history()
    return result, history


async def test_pre_change_history_replays_under_current_workflow(
    artifacts: None,
) -> None:
    """A completed H2 history (gates -> publish, REVIEWING audited after the
    publication) must replay under the current implementation: the GEN-52
    review/repair sequence is behind a patch marker, so old executions resume
    instead of failing with a nondeterminism error."""
    agent = FakeAgent(AgentRunRecord(completed=True, commands=("codex exec",)))
    verifier = FakeVerifier(VerificationOutcome(passed=True))
    pipeline_activities.set_coding_agent(agent)
    pipeline_activities.set_verification_runner(verifier)
    async with await WorkflowEnvironment.start_time_skipping() as env:
        result, history = await _generate_h2_history(env, _input(), "issue-GEN-52-compat-a")
    assert result.workflow_state == "PR_READY"
    await Replayer(workflows=[IssueWorkflow]).replay_workflow(history)


async def test_pre_change_history_blocked_on_gates_replays(
    artifacts: None,
) -> None:
    """An H2 history whose gate verification failed blocks directly (no
    repair loop existed); the legacy replay branch must reproduce that."""
    agent = FakeAgent(AgentRunRecord(completed=True, commands=("codex exec",)))
    verifier = FakeVerifier(
        VerificationOutcome(passed=False, failure_code="VERIFICATION_FAILED",
                            failure_detail="1 failed")
    )
    pipeline_activities.set_coding_agent(agent)
    pipeline_activities.set_verification_runner(verifier)
    async with await WorkflowEnvironment.start_time_skipping() as env:
        result, history = await _generate_h2_history(env, _input(), "issue-GEN-52-compat-b")
    assert result.workflow_state == "BLOCKED"
    assert result.blocking_reasons == ("VERIFICATION_FAILED: 1 failed",)
    await Replayer(workflows=[IssueWorkflow]).replay_workflow(history)


async def test_pre_change_history_blocked_on_empty_changeset_replays(
    artifacts: None,
) -> None:
    """An H2 history that reached publish and found no commits must replay
    through the legacy publish branch and block with CHANGES_EMPTY."""
    agent = FakeAgent(AgentRunRecord(completed=True, commands=("codex exec",)))
    verifier = FakeVerifier(VerificationOutcome(passed=True))
    git = FakeGitWorkspaces()
    git.ahead = 0
    pipeline_activities.set_git_workspaces(git)
    pipeline_activities.set_coding_agent(agent)
    pipeline_activities.set_verification_runner(verifier)
    async with await WorkflowEnvironment.start_time_skipping() as env:
        result, history = await _generate_h2_history(env, _input(), "issue-GEN-52-compat-c")
    assert result.workflow_state == "BLOCKED"
    assert any(reason.startswith("CHANGES_EMPTY") for reason in result.blocking_reasons)
    await Replayer(workflows=[IssueWorkflow]).replay_workflow(history)
